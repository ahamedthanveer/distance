export function findPort(unlocode: string): Port | undefined {
  return PORTS.find((p) => p.unlocode === unlocode);
}

export function searchPorts(query: string, limit = 12): Port[] {
  const q = query.trim().toLowerCase();
  if (!q) return PORTS.slice(0, limit);
  const starts: Port[] = [];
  const contains: Port[] = [];
  for (const p of PORTS) {
    const hay = `${p.name} ${p.country} ${p.unlocode}`.toLowerCase();
    if (hay.startsWith(q) || p.name.toLowerCase().startsWith(q) || p.unlocode.toLowerCase().startsWith(q)) {
      starts.push(p);
    } else if (hay.includes(q)) {
      contains.push(p);
    }
    if (starts.length >= limit) break;
  }
  return [...starts, ...contains].slice(0, limit);
}
